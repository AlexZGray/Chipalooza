"""Assemble self-contained ngspice corner libraries for the Sky130 devices this DAC uses
(nfet_01v8, pfet_01v8, res_high_po_*, res_xhigh_po_*, cap_mim_m3_1) from
fossi-foundation/skywater-pdk-libs-sky130_fd_pr (Apache-2.0).
Applies micron-to-metre scaling on the MOSFET model instance lines (so no .option scale is needed).
Device multiplicity comes from the instance m= that the xschem sky130 symbols emit."""
import os, re, sys
U, OUT = sys.argv[1], sys.argv[2]
INC = re.compile(r'^\s*\.include\s+"?([^"\s]+)"?', re.I)
SC = {'l': '1u', 'w': '1u', 'ad': '1p', 'as': '1p', 'pd': '1u', 'ps': '1u', 'sa': '1u', 'sb': '1u', 'sd': '1u'}

def fix_inst(line):
    if not re.match(r'^m\S*\s', line, re.I):
        return line
    for k, s in SC.items():
        line = re.sub(r'\b%s\s*=\s*\{%s\}' % (k, k), '%s={%s*%s}' % (k, k, s), line)
    return line

def inline(path, out, seen):
    path = os.path.normpath(path)
    if path in seen:
        return
    seen.add(path)
    d = os.path.dirname(path)
    out.append(f"* SOURCE {os.path.relpath(path, U)}\n")
    for line in open(path, newline=''):
        line = line.replace('\r', '')
        m = INC.match(line)
        if m:
            inline(os.path.join(d, m.group(1)), out, seen)
            continue
        out.append(fix_inst(line))

RC = {"tt": "res_typical__cap_typical", "hh": "res_high__cap_high", "ll": "res_low__cap_low"}
RES = ["res_high_po/sky130_fd_pr__res_high_po_0p35", "res_high_po/sky130_fd_pr__res_high_po_0p69",
       "res_high_po/sky130_fd_pr__res_high_po_1p41", "res_high_po/sky130_fd_pr__res_high_po_2p85",
       "res_high_po/sky130_fd_pr__res_high_po_5p73", "res_xhigh_po/sky130_fd_pr__res_xhigh_po_0p35",
       "res_xhigh_po/sky130_fd_pr__res_xhigh_po_0p69", "res_xhigh_po/sky130_fd_pr__res_xhigh_po_1p41",
       "res_xhigh_po/sky130_fd_pr__res_xhigh_po_2p85", "res_xhigh_po/sky130_fd_pr__res_xhigh_po_5p73",
       "res_xhigh_po/sky130_fd_pr__res_xhigh_po__base", "cap_mim_m3/sky130_fd_pr__cap_mim_m3_1"]

def corner(name, mos, rc, mm):
    o = [f"* Sky130 subset, corner {name}: MOS {mos}, R/C {rc}, mismatch switch {mm}.\n",
         "* Generated by flatten_models.py from fossi-foundation/skywater-pdk-libs-sky130_fd_pr.\n",
         f".param MC_MM_SWITCH={mm} MC_PR_SWITCH=0\n"]
    for dev in ("nfet_01v8", "pfet_01v8"):
        o.append(f".param sky130_fd_pr__{dev}__dlc_rotweak=0\n")
    seen = set()
    inline(f"{U}/models/parameters/lod.spice", o, seen)
    for dev in ("nfet_01v8", "pfet_01v8"):
        inline(f"{U}/cells/{dev}/sky130_fd_pr__{dev}__{mos}.corner.spice", o, seen)
        inline(f"{U}/cells/{dev}/sky130_fd_pr__{dev}__mismatch.corner.spice", o, seen)
    inline(f"{U}/models/corners/{mos}/nonfet.spice", o, seen)
    inline(f"{U}/models/r+c/{rc}.spice", o, seen)
    inline(f"{U}/models/r+c/{rc}__lin.spice", o, seen)
    for p in ("models/parasitics/sky130_fd_pr__model__parasitic__res_po.model.spice",):
        if os.path.exists(f"{U}/{p}"): inline(f"{U}/{p}", o, seen)
    for f in RES:
        p = f"{U}/cells/{f}.model.spice"
        if os.path.exists(p): inline(p, o, seen)
    return "".join(o)

os.makedirs(OUT, exist_ok=True)
CORNERS = {"tt": ("tt", "tt", 0), "ss": ("ss", "tt", 0), "ff": ("ff", "tt", 0), "sf": ("sf", "tt", 0),
           "fs": ("fs", "tt", 0), "hh": ("tt", "hh", 0), "ll": ("tt", "ll", 0), "mc": ("tt", "tt", 1)}
with open(f"{OUT}/sky130.lib.spice", "w") as lib:
    lib.write("* Sky130 corner library (subset) for ngspice. Sections: " + " ".join(CORNERS) + "\n")
    lib.write("* mc = typical process with device mismatch enabled (MC_MM_SWITCH=1).\n\n")
    for c, (mos, rc, mm) in CORNERS.items():
        open(f"{OUT}/sky130_{c}.spice", "w").write(corner(c, mos, RC[rc], mm))
        lib.write(f".lib {c}\n.include \"sky130_{c}.spice\"\n.endl {c}\n\n")
print("ok")
